rng = np.random.default_rng(42)
S = 256
yy, xx = np.mgrid[0:S, 0:S].astype("float32")

def blob(cx, cy, wx, wy):
    return np.exp(-(((xx - cx) / wx) ** 2 + ((yy - cy) / wy) ** 2))

def make_xray(pneumonia):
    img = 95 + 55 * np.exp(-((xx - S / 2) ** 2) / (2 * (S * 0.28) ** 2))   # body
    img += 22 * np.exp(-((xx - S / 2) ** 2) / (2 * 6 ** 2))                 # spine
    lungs = np.zeros((S, S), np.float32)
    centers = []
    for cx in (S * 0.34 + rng.normal(0, 4), S * 0.66 + rng.normal(0, 4)):
        cy = S * 0.48 + rng.normal(0, 5)
        ax_, ay = S * 0.14 * rng.uniform(.9, 1.1), S * 0.30 * rng.uniform(.9, 1.1)
        r2 = ((xx - cx) / ax_) ** 2 + ((yy - cy) / ay) ** 2
        lungs += np.exp(-r2 ** 2)
        centers.append((cx, cy, ax_, ay))
    lungs = np.clip(lungs, 0, 1)
    img -= 65 * lungs                                                       # air = darker
    img += 10 * np.clip(np.sin(yy / 6), 0, 1) * lungs                       # ribs
    img += 35 * blob(S * 0.57, S * 0.62, S * 0.10, S * 0.14)                # heart
    n = rng.integers(2, 6) if pneumonia else rng.integers(0, 2)             # opacities
    for _ in range(n):
        cx, cy, ax_, ay = centers[rng.integers(0, 2)]
        bx, by = cx + rng.normal(0, ax_ * .5), cy + rng.normal(0, ay * .5)
        amp = rng.uniform(35, 70) if pneumonia else rng.uniform(5, 15)
        img += amp * blob(bx, by, rng.uniform(12, 30), rng.uniform(12, 35)) * lungs
    img = cv2.GaussianBlur(img, (0, 0), 2.5)
    img += rng.normal(0, 5, img.shape) + rng.normal(0, 8)                   # noise, brightness
    return np.clip(img, 0, 255).astype("uint8")

