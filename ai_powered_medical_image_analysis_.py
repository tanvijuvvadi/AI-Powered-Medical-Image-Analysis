def make_augmentation():
    # No horizontal flip: it would put the heart on the wrong side
    return models.Sequential([
        layers.RandomRotation(0.04), layers.RandomTranslation(0.05, 0.05),
        layers.RandomZoom(0.1), layers.RandomContrast(0.1)], name="augmentation")

def compile_model(model, lr):
    model.compile(optimizer=tf.keras.optimizers.Adam(lr), loss="binary_crossentropy",
                  metrics=["accuracy", tf.keras.metrics.Precision(name="precision"),
                           tf.keras.metrics.Recall(name="recall"),
                           tf.keras.metrics.AUC(name="auc")])
    return model

base = tf.keras.applications.MobileNetV2(input_shape=IMG_SIZE + (3,),
                                         include_top=False, weights="imagenet")
base.trainable = False   # phase 1: backbone frozen

inputs = layers.Input(shape=IMG_SIZE + (3,))
x = make_augmentation()(inputs)
x = layers.Rescaling(1 / 127.5, offset=-1, name="preprocess")(x)   # -> [-1, 1]
x = base(x, training=False)
x = layers.GlobalAveragePooling2D(name="gap")(x)
x = layers.Dropout(0.3, name="dropout")(x)
outputs = layers.Dense(1, activation="sigmoid", name="pred")(x)
model = compile_model(models.Model(inputs, outputs, name="pneumonia_mobilenetv2"), 1e-3)
model.summary()

