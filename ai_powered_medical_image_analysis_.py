def make_gradcam(model, batch):
    backbone = next(l for l in model.layers if isinstance(l, tf.keras.Model)
                    and l.name.startswith("mobilenet"))
    conv_model = tf.keras.Model(backbone.input, backbone.get_layer("out_relu").output)
    x = model.get_layer("preprocess")(tf.convert_to_tensor(batch))
    with tf.GradientTape() as tape:
        conv_out = conv_model(x)
        tape.watch(conv_out)
        score = model.get_layer("pred")(model.get_layer("gap")(conv_out))[:, 0]
    grads = tape.gradient(score, conv_out)
    weights = tf.reduce_mean(grads, axis=(1, 2), keepdims=True)
    cam = tf.nn.relu(tf.reduce_sum(weights * conv_out, axis=-1))[0].numpy()
    return cam / (cam.max() + 1e-8)

def gradcam_figure(image_rgb, true_label, save_as=None):
    batch = image_rgb[np.newaxis].astype("float32")
    prob = float(model.predict(batch, verbose=0)[0][0])
    cam = make_gradcam(model, batch)
    base_img = image_rgb.astype("uint8")
    hm = cv2.applyColorMap(np.uint8(255 * cv2.resize(cam, IMG_SIZE)), cv2.COLORMAP_JET)
    hm = cv2.cvtColor(hm, cv2.COLOR_BGR2RGB)
    overlay = cv2.addWeighted(base_img, 0.6, hm, 0.4, 0)
    fig, axes = plt.subplots(1, 2, figsize=(8, 4))
    axes[0].imshow(base_img); axes[0].set_title(f"Actual: {CLASS_NAMES[true_label]}")
    axes[1].imshow(overlay)
    axes[1].set_title(f"Pred: {CLASS_NAMES[int(prob >= 0.5)]} ({prob:.2f})")
    for a in axes: a.axis("off")
    if save_as: fig.savefig(save_as, dpi=150, bbox_inches="tight")
    plt.show()

